static double now_sec(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return ts.tv_sec + ts.tv_nsec / 1e9;
}

// ============================================================
// Deterministic hash: identical (model, hw, plan) -> identical hash
// ============================================================
void vbs_specializer_compute_hash(
    const vbs_graph_t *graph,
    const vbs_system_profile_t *sys,
    const vbs_execution_plan_t *plan,
    char *out_hex, size_t out_cap
) {
    CC_SHA256_CTX ctx;
    CC_SHA256_Init(&ctx);

    CC_SHA256_Update(&ctx, graph->fingerprint, (CC_LONG)strlen(graph->fingerprint));

    for (size_t i = 0; i < sys->n_gpus; i++) {
        CC_SHA256_Update(&ctx, sys->gpus[i].name, (CC_LONG)strlen(sys->gpus[i].name));
        CC_SHA256_Update(&ctx, &sys->gpus[i].total_vram_bytes, sizeof(uint64_t));
        CC_SHA256_Update(&ctx, &sys->gpus[i].sm_count, sizeof(uint32_t));
        CC_SHA256_Update(&ctx, &sys->gpus[i].warp_size, sizeof(uint32_t));
    }
    CC_SHA256_Update(&ctx, &sys->cpu.total_ram_bytes, sizeof(uint64_t));
    CC_SHA256_Update(&ctx, &sys->cpu.physical_cores, sizeof(uint32_t));
    CC_SHA256_Update(&ctx, &sys->cpu.has_avx2, sizeof(bool));
    CC_SHA256_Update(&ctx, &sys->cpu.has_avx512, sizeof(bool));
    CC_SHA256_Update(&ctx, &sys->cpu.has_neon, sizeof(bool));

    for (size_t i = 0; i < plan->n_plans; i++) {
        CC_SHA256_Update(&ctx, &plan->plans[i].strategy, sizeof(int));
        CC_SHA256_Update(&ctx, &plan->plans[i].tile_rows, sizeof(uint32_t));
        CC_SHA256_Update(&ctx, &plan->plans[i].tile_cols, sizeof(uint32_t));
        CC_SHA256_Update(&ctx, &plan->plans[i].prefetch_depth, sizeof(uint32_t));
    }

    unsigned char digest[CC_SHA256_DIGEST_LENGTH];
    CC_SHA256_Final(digest, &ctx);
    for (int i = 0; i < CC_SHA256_DIGEST_LENGTH && (size_t)(i * 2 + 2) < out_cap; i++) {
        sprintf(out_hex + i * 2, "%02x", digest[i]);
    }
}

// ============================================================
// Cache lookup
// ============================================================
static bool file_exists(const char *p) {
    struct stat st;
    return stat(p, &st) == 0;
}

vbs_specialized_binary_t *vbs_specializer_load_cached(
    const char *hash,
    const char *cache_dir
) {
    char bin_path[640];
    snprintf(bin_path, sizeof(bin_path), "%s/verum_%s.so", cache_dir, hash);
    if (!file_exists(bin_path)) return NULL;
    return vbs_specializer_load(bin_path, hash);
}

