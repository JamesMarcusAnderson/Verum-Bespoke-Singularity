#!/bin/sh
# build-spirv.sh — compile the Vulkan GLSL kernels to SPIR-V and generate
# kernels/vulkan_kernels.spv.h (checked in, so the repo builds offline with
# no Vulkan SDK or glslang installed).
#
# Requires: glslangValidator, spirv-val (from the Vulkan SDK or the
#   `glslang-tools` / `spirv-tools` distro packages).
# Usage: sh kernels/build-spirv.sh   (run from the repo root)
#
# Every module is validated with spirv-val; the script aborts if any
# module fails validation. Target is Vulkan 1.0 / SPIR-V 1.0 for the
# widest device support (all kernels use only core GLSL 450 features).

set -e
cd "$(dirname "$0")/.."  # repo root

command -v glslangValidator >/dev/null 2>&1 || {
    echo "build-spirv.sh: glslangValidator not found" >&2; exit 1; }
command -v spirv-val >/dev/null 2>&1 || {
    echo "build-spirv.sh: spirv-val not found" >&2; exit 1; }

TMPD="$(mktemp -d)"
trap 'rm -rf "$TMPD"' EXIT INT TERM

OUT="kernels/vulkan_kernels.spv.h"
{
    echo "/* Auto-generated by kernels/build-spirv.sh — do not edit by hand."
    echo " * Precompiled SPIR-V for the Vulkan compute kernels in"
    echo " * kernels/vulkan/ GLSL sources (the source of truth)."
    echo " * Target: Vulkan 1.0 / SPIR-V 1.0. Every module passed spirv-val"
    echo " * at generation time. The engine additionally runs its in-repo"
    echo " * structural validator (spirv_validate) before creating a shader"
    echo " * module from any of these blobs."
    echo " */"
    echo "#ifndef VULKAN_KERNELS_SPV_H"
    echo "#define VULKAN_KERNELS_SPV_H"
    echo ""
    echo "#include <stddef.h>"
    echo "#include <stdint.h>"
    echo ""
} > "$OUT"

for src in kernels/vulkan/*.comp; do
    name="$(basename "$src" .comp)"
    spv="$TMPD/$name.spv"
    glslangValidator -V --target-env vulkan1.0 -Ikernels/vulkan \
        -o "$spv" "$src"
    spirv-val "$spv"
    words="$(python3 - "$spv" <<'PY'
import struct, sys
data = open(sys.argv[1], 'rb').read()
assert len(data) % 4 == 0
words = struct.unpack('<%dI' % (len(data) // 4), data)
print(len(words))
for i in range(0, len(words), 8):
    print('    ' + ', '.join('0x%08xu' % w for w in words[i:i+8]) + ',')
PY
)"
    count="$(printf '%s\n' "$words" | head -n 1)"
    body="$(printf '%s\n' "$words" | tail -n +2)"
    {
        echo "/* $name.comp — $count words */"
        echo "static const uint32_t vbs_spv_${name}[] = {"
        printf '%s\n' "$body"
        echo "};"
        echo "static const size_t vbs_spv_${name}_words = ${count}u;"
        echo ""
    } >> "$OUT"
    echo "ok: $name ($count words)"
done

{
    echo "#endif /* VULKAN_KERNELS_SPV_H */"
} >> "$OUT"

echo "wrote $OUT"
