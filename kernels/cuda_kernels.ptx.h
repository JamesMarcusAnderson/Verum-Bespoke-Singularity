"// =========================================================================\n"
"// SwiGLU Activation (silu(gate) * up)\n"
"// =========================================================================\n"
".visible .entry silu_mul(\n"
"    .param .u64 gate, .param .u64 up, .param .u64 out,\n"
"    .param .u32 n\n"
") {\n"
"    .reg .pred %p<2>;\n"
"    .reg .b32 %r<4>;\n"
"    .reg .f32 %f<6>;\n"
"    .reg .b64 %rd<8>;\n"
"\n"
"    ld.param.u64 %rd1, [gate];\n"
"    ld.param.u64 %rd2, [up];\n"
"    ld.param.u64 %rd3, [out];\n"
"    ld.param.u32 %r1, [n];\n"
"\n"
"    mov.u32 %r2, %ctaid.x;\n"
"    mov.u32 %r3, %ntid.x;\n"
"    mov.u32 %r4, %tid.x;\n"
"    mad.lo.s32 %r2, %r2, %r3, %r4;\n"
"\n"
"    setp.ge.u32 %p1, %r2, %r1;\n"
"    @%p1 bra $L_SILU_EXIT;\n"
"\n"
"    mul.wide.u32 %rd4, %r2, 4;\n"
"    add.s64 %rd5, %rd1, %rd4;\n"
"    ld.global.f32 %f1, [%rd5];\n" // gv
"    add.s64 %rd6, %rd2, %rd4;\n"
"    ld.global.f32 %f2, [%rd6];\n" // uv
"\n"
"    // silu = gv / (1 + exp(-gv))\n"
"    neg.f32 %f3, %f1;\n"
"    mul.f32 %f3, %f3, 0f3FB8AA3B;\n" // -gv * log2(e)
"    ex2.approx.f32 %f4, %f3;\n"
"    add.f32 %f4, %f4, 1.0;\n"
"    rcp.approx.f32 %f4, %f4;\n"
"    mul.f32 %f5, %f1, %f4;\n"
"    mul.f32 %f5, %f5, %f2;\n"       // silu(gv) * uv
"\n"
"    add.s64 %rd7, %rd3, %rd4;\n"
"    st.global.f32 [%rd7], %f5;\n"
"\n"
"$L_SILU_EXIT:\n"
"    ret;\n"
"}\n";

