"// =========================================================================\n"
"// On-GPU Argmax Sampling (Writes single uint32 token)\n"
"// =========================================================================\n"
".visible .entry argmax_write_token(\n"
"    .param .u64 logits, .param .u64 out_token, .param .u32 vocab_size\n"
") {\n"
"    .reg .pred %p<3>;\n"
"    .reg .b32 %r<10>;\n"
"    .reg .f32 %f<6>;\n"
"    .reg .b64 %rd<8>;\n"
"\n"
"    ld.param.u64 %rd1, [logits];\n"
"    ld.param.u64 %rd2, [out_token];\n"
"    ld.param.u32 %r1, [vocab_size];\n"
"\n"
"    mov.u32 %r2, %tid.x;\n"
"    mov.f32 %f1, 0fFF7FFFFF;\n"       // -FLT_MAX
"    mov.u32 %r3, 0;\n"
"    mov.u32 %r4, %r2;\n"
"\n"
"$L_ARGMAX_LOOP:\n"
"    setp.ge.u32 %p1, %r4, %r1;\n"
"    @%p1 bra $L_ARGMAX_REDUCE;\n"
"\n"
"    mul.wide.u32 %rd4, %r4, 4;\n"
"    add.s64 %rd5, %rd1, %rd4;\n"
"    ld.global.f32 %f2, [%rd5];\n"
"    setp.gt.f32 %p2, %f2, %f1;\n"
"    @%p2 mov.f32 %f1, %f2;\n"
"    @%p2 mov.u32 %r3, %r4;\n"
"\n"
"    add.s32 %r4, %r4, 32;\n"
"    bra $L_ARGMAX_LOOP;\n"
"\n"
"$L_ARGMAX_REDUCE:\n"
"    // Warp reduce to find global maximum\n"
"    shfl.sync.down.b32 %f3, %f1, 16, 0x1f, 0xffffffff;\n"
"    shfl.sync.down.b32 %r5, %r3, 16, 0x1f, 0xffffffff;\n"
"    setp.gt.f32 %p1, %f3, %f1;\n"
"    @%p1 mov.f32 %f1, %f3;\n"
"    @%p1 mov.u32 %r3, %r5;\n"
"\n"
"    shfl.sync.down.b32 %f3, %f1, 8, 0x1f, 0xffffffff;\n"
"    shfl.sync.down.b32 %r5, %r3, 8, 0x1f, 0xffffffff;\n"
"    setp.gt.f32 %p1, %f3, %f1;\n"
"    @%p1 mov.f32 %f1, %f3;\n"
"    @%p1 mov.u32 %r3, %r5;\n"
"\n"
"    shfl.sync.down.b32 %f3, %f1, 4, 0x1f, 0xffffffff;\n"
"    shfl.sync.down.b32 %r5, %r3, 4, 0x1f, 0xffffffff;\n"
"    setp.gt.f32 %p1, %f3, %f1;\n"
"    @%p1 mov.f32 %f1, %f3;\n"
"    @%p1 mov.u32 %r3, %r5;\n"
"\n"
"    shfl.sync.down.b32 %f3, %f1, 2, 0x1f, 0xffffffff;\n"
"    shfl.sync.down.b32 %r5, %r3, 2, 0x1f, 0xffffffff;\n"
"    setp.gt.f32 %p1, %f3, %f1;\n"
"    @%p1 mov.f32 %f1, %f3;\n"
"    @%p1 mov.u32 %r3, %r5;\n"
"\n"
"    shfl.sync.down.b32 %f3, %f1, 1, 0x1f, 0xffffffff;\n"
"    shfl.sync.down.b32 %r5, %r3, 1, 0x1f, 0xffffffff;\n"
"    setp.gt.f32 %p1, %f3, %f1;\n"
"    @%p1 mov.f32 %f1, %f3;\n"
"    @%p1 mov.u32 %r3, %r5;\n"
"\n"
"    // Lane 0 writes selected token integer\n"
"    setp.ne.u32 %p1, %r2, 0;\n"
"    @%p1 bra $L_ARGMAX_EXIT;\n"
"    st.global.u32 [%rd2], %r3;\n"
"\n"
"$L_ARGMAX_EXIT:\n"
"    ret;\n"
"}\n";

