#!/bin/sh
# build-kernels.sh — compile the GPU compute kernels from GLSL to
# SPIR-V modules and pack them into kernels/gpu_kernels.spv.h, which
# is checked in so the repo builds offline with no GPU SDK installed.
#
# Requires: glslangValidator, spirv-val (from a GPU SDK or the
#   `glslang-tools` / `spirv-tools` distro packages).
# Usage: sh kernels/build-kernels.sh   (run from the repo root)
#
# Every module is validated with spirv-val; the script aborts if any
# module fails. Target is Vulkan 1.0 / SPIR-V 1.0 for the widest
# device support (all kernels use only core GLSL 450 features).

set -e
cd "$(dirname "$0")/.."  # repo root

for tool in glslangValidator spirv-val; do
    command -v "$tool" >/dev/null 2>&1 || {
        echo "build-kernels.sh: $tool not found" >&2; exit 1; }
done

TMPD="$(mktemp -d)"
trap 'rm -rf "$TMPD"' EXIT INT TERM

OUT="kernels/gpu_kernels.spv.h"
{
    echo "/* Auto-generated by kernels/build-kernels.sh — do not edit by hand."
    echo " * Precompiled SPIR-V for the GPU compute kernels in"
    echo " * kernels/gpu/ GLSL sources (the source of truth)."
    echo " * Target: Vulkan 1.0 / SPIR-V 1.0. Every module passed spirv-val"
    echo " * at generation time. The engine additionally runs its in-repo"
    echo " * structural validator (vbs_kernel_validate) before creating a"
    echo " * shader module from any of these blobs."
    echo " */"
    echo "#ifndef GPU_KERNELS_SPV_H"
    echo "#define GPU_KERNELS_SPV_H"
    echo ""
    echo "#include <stddef.h>"
    echo "#include <stdint.h>"
    echo ""
} > "$OUT"

for src in kernels/gpu/*.comp; do
    name="$(basename "$src" .comp)"
    spv="$TMPD/$name.spv"
    glslangValidator -V --target-env vulkan1.0 -Ikernels/gpu \
        -o "$spv" "$src"
    spirv-val "$spv"
    words="$(python3 - "$spv" <<'PY'
import struct, sys
data = open(sys.argv[1], 'rb').read()
assert len(data) % 4 == 0
words = struct.unpack('<%dI' % (len(data) // 4), data)
print(len(words))
for i in range(0, len(words), 8):
    print('    ' + ', '.join('0x%08xu' % w for w in words[i:i+8]) + ',')
PY
)"
    count="$(printf '%s\n' "$words" | head -n 1)"
    body="$(printf '%s\n' "$words" | tail -n +2)"
    {
        echo "/* $name.comp — $count words */"
        echo "static const uint32_t vbs_kernel_${name}[] = {"
        printf '%s\n' "$body"
        echo "};"
        echo "static const size_t vbs_kernel_${name}_words = ${count}u;"
        echo ""
    } >> "$OUT"
    echo "ok: $name ($count words)"
done

{
    echo "#endif /* GPU_KERNELS_SPV_H */"
} >> "$OUT"

echo "wrote $OUT"
